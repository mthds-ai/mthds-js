// Generates src/method-tree/case-folding-table.ts, the Unicode full case folding table the
// method tree's collision rule needs (mthds/docs/spec/method-tree.md, "Tree Paths"): every entry
// of status C or F of a CaseFolding.txt, with no locale tailoring, so the Turkic entries (status
// T) and the simple foldings (status S) are left out. JavaScript has no full case folding of its
// own, `toLowerCase` being a case conversion and not a folding, so this package carries the table.
//
//   node scripts/gen-case-folding.mjs [<CaseFolding.txt>]      writes the table
//   node scripts/gen-case-folding.mjs --check [<CaseFolding.txt>]  fails when the committed table differs
//
// The source defaults to the copy committed beside this script, scripts/unicode/, whose header
// names its Unicode version; the generated module records that version. To move to a later
// version, download its CaseFolding.txt from https://www.unicode.org/Public/<version>/ucd/ into
// scripts/unicode/, delete the old copy, and run this script with no argument.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const UNICODE_DIR = new URL("./unicode/", import.meta.url);
const TABLE_URL = new URL("../src/method-tree/case-folding-table.ts", import.meta.url);
const HEADER_PATTERN = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt$/;

function defaultSource() {
  const sources = readdirSync(UNICODE_DIR).filter((name) => /^CaseFolding-.*\.txt$/.test(name));
  if (sources.length !== 1) {
    throw new Error(
      `expected exactly one CaseFolding-<version>.txt in ${fileURLToPath(UNICODE_DIR)}, found ${sources.length}`,
    );
  }
  return fileURLToPath(new URL(sources[0], UNICODE_DIR));
}

/** Parse CaseFolding.txt into its version and its C and F entries, in code point order. */
function parseCaseFolding(text) {
  const lines = text.split("\n");
  const header = HEADER_PATTERN.exec(lines[0].trim());
  if (!header) {
    throw new Error(`the first line of the source is not a CaseFolding.txt header: ${lines[0]}`);
  }
  const entries = [];
  for (const line of lines) {
    const content = line.split("#", 1)[0].trim();
    if (!content) continue;
    const fields = content.split(";").map((field) => field.trim());
    const [code, status, mapping] = fields;
    if (status !== "C" && status !== "F") continue;
    const codePoint = Number.parseInt(code, 16);
    const mapped = mapping.split(/\s+/).map((hex) => Number.parseInt(hex, 16));
    if (!Number.isInteger(codePoint) || mapped.some((value) => !Number.isInteger(value))) {
      throw new Error(`unreadable entry: ${line}`);
    }
    entries.push([codePoint, ...mapped]);
  }
  entries.sort((left, right) => left[0] - right[0]);
  for (let index = 1; index < entries.length; index += 1) {
    if (entries[index][0] === entries[index - 1][0]) {
      throw new Error(`code point ${entries[index][0].toString(16)} has two C or F entries`);
    }
  }
  return { version: header[1], entries };
}

function hex(value) {
  return `0x${value.toString(16).padStart(4, "0")}`;
}

async function renderTable(sourceText) {
  const { version, entries } = parseCaseFolding(sourceText);
  const rows = entries.map((entry) => `  [${entry.map(hex).join(", ")}],`).join("\n");
  const module = `// GENERATED by scripts/gen-case-folding.mjs from CaseFolding-${version}.txt. Do not edit by hand:
// run \`node scripts/gen-case-folding.mjs\` to regenerate it, and \`--check\` to verify it.

/** The Unicode version of the CaseFolding.txt this table was generated from. */
export const CASE_FOLDING_UNICODE_VERSION = "${version}";

/**
 * Unicode full case folding: every entry of status C or F of CaseFolding.txt, with no locale
 * tailoring, each written as its code point followed by the code points it folds to.
 */
export const FULL_CASE_FOLDING: readonly (readonly number[])[] = [
${rows}
];
`;
  const options = (await prettier.resolveConfig(fileURLToPath(TABLE_URL))) ?? {};
  return prettier.format(module, { ...options, parser: "typescript" });
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const positional = args.filter((arg) => arg !== "--check");
  const sourcePath = positional[0] ?? defaultSource();
  const rendered = await renderTable(readFileSync(sourcePath, "utf-8"));
  if (check) {
    const committed = readFileSync(TABLE_URL, "utf-8");
    if (committed !== rendered) {
      process.stderr.write(
        `${fileURLToPath(TABLE_URL)} is not what ${sourcePath} generates; run node scripts/gen-case-folding.mjs\n`,
      );
      process.exit(1);
    }
    process.stdout.write(`${fileURLToPath(TABLE_URL)} matches ${sourcePath}\n`);
    return;
  }
  writeFileSync(TABLE_URL, rendered);
  process.stdout.write(`wrote ${fileURLToPath(TABLE_URL)} from ${sourcePath}\n`);
}

await main();
